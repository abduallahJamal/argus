// argus/report.mjs — turn raw run records into statistics you can defend:
// median + IQR + bootstrap CI, normalized scores, and a generated markdown/HTML report.
// Every number in the README comes from here, so the README cannot drift from the data.
import fs from "node:fs";

const METRICS = [
  { id: "wall_s", label: "wall time (s)", lowerBetter: true },
  { id: "turns", label: "turns", lowerBetter: true },
  { id: "cost", label: "cost ($)", lowerBetter: true },
  { id: "tokens", label: "tokens (k)", lowerBetter: true, scale: 1 / 1000 },
  { id: "accuracy", label: "accuracy", lowerBetter: false, pct: true },
];

export function normalizeRow(r) {
  const tokens = typeof r.tokens === "object" && r.tokens !== null
    ? Object.values(r.tokens).reduce((a, b) => a + (Number(b) || 0), 0)
    : (r.tokens ?? (r.in || 0) + (r.cache_w || 0) + (r.cache_r || 0) + (r.out || 0));
  let points = r.points, max = r.max, weighted = r.weighted;
  if (points === undefined && typeof r.score === "string") {
    const [p, m] = r.score.split("/").map(Number);
    points = p; max = m; weighted = m ? p / m : null;
  }
  if (max && weighted === undefined) weighted = points / max;
  return {
    arm: r.arm, task: r.task, rep: String(r.rep), model: r.model || null,
    wall_s: Number(r.wall_s), turns: Number(r.turns ?? 0), cost: Number(r.cost ?? 0),
    tokens, points, max, accuracy: weighted ?? 0,
    error: !!r.err, miss: r.miss || [], tools: r.tools || [],
  };
}

export function loadRuns(file) {
  const text = fs.readFileSync(file, "utf8");
  const rows = text.trim().split("\n").filter(Boolean).map(l => JSON.parse(l));
  return rows.map(normalizeRow);
}

export function median(xs) {
  if (!xs.length) return NaN;
  const a = [...xs].sort((x, y) => x - y);
  const m = a.length >> 1;
  return a.length % 2 ? a[m] : (a[m - 1] + a[m]) / 2;
}
export function quantile(xs, q) {
  if (!xs.length) return NaN;
  const a = [...xs].sort((x, y) => x - y);
  const pos = (a.length - 1) * q;
  const lo = Math.floor(pos), hi = Math.ceil(pos);
  return lo === hi ? a[lo] : a[lo] + (a[hi] - a[lo]) * (pos - lo);
}

/** Deterministic bootstrap CI for the median. No dependencies, reproducible seed. */
export function bootstrapCI(xs, { reps = 2000, seed = 12345 } = {}) {
  if (xs.length < 3) return [NaN, NaN];
  let s = seed;
  const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
  const meds = [];
  for (let i = 0; i < reps; i++) {
    const sample = new Array(xs.length);
    for (let j = 0; j < xs.length; j++) sample[j] = xs[Math.floor(rnd() * xs.length)];
    meds.push(median(sample));
  }
  return [quantile(meds, 0.025), quantile(meds, 0.975)];
}

export function summarize(rows, groupBy = "arm") {
  const groups = new Map();
  for (const r of rows) {
    const k = r[groupBy];
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(r);
  }
  const out = [];
  for (const [k, rs] of groups) {
    const o = { key: k, n: rs.length };
    for (const m of METRICS) {
      const vals = rs.map(r => (r[m.id] ?? 0) * (m.scale || 1)).filter(v => Number.isFinite(v));
      o[m.id] = {
        median: median(vals), mean: vals.reduce((a, b) => a + b, 0) / (vals.length || 1),
        iqr: [quantile(vals, 0.25), quantile(vals, 0.75)], ci: bootstrapCI(vals),
      };
    }
    o.errors = rs.filter(r => r.error).length;
    o.points = rs.reduce((a, r) => a + (r.points || 0), 0);
    o.max = rs.reduce((a, r) => a + (r.max || 0), 0);
    out.push(o);
  }
  return out.sort((a, b) => b.accuracy.median - a.accuracy.median || a.wall_s.median - b.wall_s.median);
}

const f = (x, d = 1) => (Number.isFinite(x) ? x.toFixed(d) : "–");
const pct = x => (Number.isFinite(x) ? (x * 100).toFixed(1) + "%" : "–");

export function toMarkdown(rows, { title = "argus benchmark", baseline = "none", generated = true } = {}) {
  const overall = summarize(rows);
  const tasks = [...new Set(rows.map(r => r.task))];
  const L = [];
  L.push(`## ${title}`, "");
  if (generated) L.push(`_Generated by \`argus report\` from ${rows.length} runs (${[...new Set(rows.map(r => r.model).filter(Boolean))].join(", ") || "model not recorded"}). Median values; [95% CI] from a bootstrap of the median._`, "");
  L.push(`| arm | runs | accuracy (weighted) | wall s | turns | cost $ | tokens k | errors |`);
  L.push(`|---|---|---|---|---|---|---|---|`);
  for (const a of overall) {
    L.push(`| **${a.key}** | ${a.n} | ${pct(a.accuracy.median)} [${pct(a.accuracy.ci[0])}–${pct(a.accuracy.ci[1])}] | ${f(a.wall_s.median)} [${f(a.wall_s.iqr[0])}–${f(a.wall_s.iqr[1])}] | ${f(a.turns.median, 0)} | ${f(a.cost.median, 2)} | ${f(a.tokens.median, 0)} | ${a.errors} |`);
  }
  const base = overall.find(a => a.key === baseline);
  if (base) {
    L.push("", `Deltas against \`${baseline}\` (negative = better, except accuracy):`, "");
    L.push(`| arm | wall | turns | cost | tokens | accuracy |`);
    L.push(`|---|---|---|---|---|---|`);
    for (const a of overall) {
      if (a.key === baseline) continue;
      const d = (m) => {
        const b = base[m].median || 1;
        const v = ((a[m].median - base[m].median) / b) * 100;
        return (v > 0 ? "+" : "") + v.toFixed(0) + "%";
      };
      const da = ((a.accuracy.median - base.accuracy.median) * 100).toFixed(1) + " pp";
      L.push(`| ${a.key} | ${d("wall_s")} | ${d("turns")} | ${d("cost")} | ${d("tokens")} | ${da} |`);
    }
  }
  L.push("", `### Per task`, "");
  L.push(`| task | arm | runs | accuracy | wall s | turns | cost $ | misses |`);
  L.push(`|---|---|---|---|---|---|---|---|`);
  for (const t of tasks) {
    const sub = summarize(rows.filter(r => r.task === t));
    for (const a of sub) {
      const misses = [...new Set(rows.filter(r => r.task === t && r.arm === a.key).flatMap(r => r.miss))].slice(0, 4).join(", ");
      L.push(`| ${t} | ${a.key} | ${a.n} | ${pct(a.accuracy.median)} | ${f(a.wall_s.median)} | ${f(a.turns.median, 0)} | ${f(a.cost.median, 2)} | ${misses || ""} |`);
    }
  }
  const errs = rows.filter(r => r.error);
  if (errs.length) L.push("", `> ${errs.length} runs ended in an error and are included as-is: ${errs.map(r => `${r.arm}/${r.task}/${r.rep}`).join(", ")}`);
  L.push("", `Reproduce: \`argus report <results.jsonl>\` — the tables above are generated, never typed by hand.`, "");
  return L.join("\n");
}

export function toHtml(rows, { title = "argus benchmark" } = {}) {
  const overall = summarize(rows);
  const tasks = [...new Set(rows.map(r => r.task))];
  const best = (m) => Math.max(...overall.map(a => a[m].median || 0));
  const bar = (v, max, colour) => {
    const w = max > 0 ? Math.max(2, Math.round((v / max) * 100)) : 0;
    return `<div style="background:#1b2130;border-radius:3px;height:8px;width:120px;display:inline-block;vertical-align:middle"><div style="width:${w}%;height:8px;border-radius:3px;background:${colour}"></div></div>`;
  };
  const T = (h, rs) => `<table style="border-collapse:collapse;width:100%;font-size:13px">
<thead><tr>${h.map(x => `<th style="text-align:left;padding:7px 10px;border-bottom:1px solid #2a3346;color:#8b97ad;font-weight:600">${x}</th>`).join("")}</tr></thead>
<tbody>${rs.join("")}</tbody></table>`;
  const row = cells => `<tr>${cells.map(c => `<td style="padding:7px 10px;border-bottom:1px solid #1b2130;color:#dbe3f0">${c}</td>`).join("")}</tr>`;

  const kpi = overall.map(a => `<div style="flex:1;min-width:180px;background:#111725;border:1px solid #202a3d;border-radius:10px;padding:14px">
<div style="color:#7f8da6;font-size:12px;letter-spacing:.06em;text-transform:uppercase">${a.key}</div>
<div style="font-size:26px;color:#e8eefb;margin:6px 0 2px">${pct(a.accuracy.median)}</div>
<div style="color:#7f8da6;font-size:12px">accuracy · ${f(a.wall_s.median)} s · ${f(a.cost.median, 2)} $ · ${f(a.tokens.median, 0)}k tok</div>
</div>`).join("");

  const mainRows = overall.map(a => row([
    `<b>${a.key}</b>`, `${a.n}`, pct(a.accuracy.median),
    `${f(a.wall_s.median)} ${bar(a.wall_s.median, best("wall_s"), "#5b8def")}`,
    `${f(a.turns.median, 0)} ${bar(a.turns.median, best("turns"), "#8b7cf6")}`,
    `${f(a.cost.median, 2)} ${bar(a.cost.median, best("cost"), "#e8a33d")}`,
    `${f(a.tokens.median, 0)} ${bar(a.tokens.median, best("tokens"), "#38b2a3")}`,
    a.errors,
  ]));

  const taskBlocks = tasks.map(t => {
    const sub = summarize(rows.filter(r => r.task === t));
    const rs = sub.map(a => row([`<b>${a.key}</b>`, a.n, pct(a.accuracy.median), `${f(a.wall_s.median)} s`, `${f(a.turns.median, 0)}`, `${f(a.cost.median, 2)} $`,
      [...new Set(rows.filter(r => r.task === t && r.arm === a.key).flatMap(r => r.miss))].join(", ") || "–"]));
    return `<div style="margin:22px 0"><div style="color:#c8d3e6;margin-bottom:8px;font-weight:600">${t}</div>
${T(["arm", "runs", "accuracy", "wall", "turns", "cost", "misses"], rs)}</div>`;
  }).join("");

  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${title}</title>
<meta name="viewport" content="width=device-width,initial-scale=1"></head>
<body style="margin:0;background:#0b0f18;font-family:ui-sans-serif,system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:#dbe3f0">
<div style="max-width:980px;margin:0 auto;padding:32px 20px 60px">
<div style="display:flex;align-items:baseline;gap:12px;flex-wrap:wrap">
<h1 style="font-size:22px;margin:0;color:#eef3fc">${title}</h1>
<span style="color:#7f8da6;font-size:13px">${rows.length} runs · median with bootstrap CI · generated ${new Date().toISOString().slice(0, 10)}</span>
</div>
<div style="display:flex;gap:12px;margin:18px 0 24px;flex-wrap:wrap">${kpi}</div>
${T(["arm", "runs", "accuracy", "wall time", "turns", "cost", "tokens", "errors"], mainRows)}
${taskBlocks}
<p style="color:#6d7a91;font-size:12px;margin-top:26px">Every figure is emitted by <code style="color:#9fb0cc">argus report</code> straight from the run jsonl. If a number is not here, it is not a claim.</p>
</div></body></html>`;
}
